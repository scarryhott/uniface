    @staticmethod
    def _graph(
        presentations: list[str], steps: list[LocalTranslationStepInput]
    ) -> dict[str, list[tuple[str, str]]]:
        adjacency = {item: [] for item in presentations}
        for step in steps:
            if not step.admitted_for_completion:
                continue
            adjacency[step.source].append((step.target, step.label))
            adjacency[step.target].append((step.source, step.label))
        for node in adjacency:
            adjacency[node].sort(key=lambda item: (item[0], item[1]))
        return adjacency

    @staticmethod
    def _components(
        presentations: list[str], adjacency: dict[str, list[tuple[str, str]]]
    ) -> tuple[list[list[str]], dict[str, str]]:
        remaining = set(presentations)
        components: list[list[str]] = []
        class_of: dict[str, str] = {}
        for start in presentations:
            if start not in remaining:
                continue
            queue = deque([start])
            remaining.remove(start)
            members: list[str] = []
            while queue:
                node = queue.popleft()
                members.append(node)
                for neighbor, _label in adjacency[node]:
                    if neighbor in remaining:
                        remaining.remove(neighbor)
                        queue.append(neighbor)
            members.sort()
            cid = _class_id(members)
            components.append(members)
            for member in members:
                class_of[member] = cid
        components.sort(key=lambda items: (items[0], len(items)))
        return components, class_of

    @staticmethod
    def _shortest_path(
        source: str,
        target: str,
        adjacency: dict[str, list[tuple[str, str]]],
    ) -> ReachWitness:
        if source == target:
            return ReachWitness(
                source=source,
                target=target,
                related=True,
                path=[source],
                step_labels=[],
                length=0,
                finite_local_lineage=True,
            )
        queue = deque([source])
        previous: dict[str, tuple[str, str] | None] = {source: None}
        while queue:
            node = queue.popleft()
            for neighbor, label in adjacency[node]:
                if neighbor in previous:
                    continue
                previous[neighbor] = (node, label)
                if neighbor == target:
                    queue.clear()
                    break
                queue.append(neighbor)
        if target not in previous:
            return ReachWitness(
                source=source,
                target=target,
                related=False,
                path=[],
                step_labels=[],
                length=None,
                finite_local_lineage=False,
            )
        path = [target]
        labels: list[str] = []
        current = target
        while current != source:
            parent, label = previous[current] or (source, "")
            labels.append(label)
            path.append(parent)
            current = parent
        path.reverse()
        labels.reverse()
        return ReachWitness(
            source=source,
            target=target,
            related=True,
            path=path,
            step_labels=labels,
            length=len(labels),
            finite_local_lineage=True,
        )

    @classmethod
    def evaluate(cls, data: CompletionSystemCreate) -> CompletionEvaluation:
        adjacency = cls._graph(data.presentations, data.steps)
        components, class_of = cls._components(data.presentations, adjacency)

        completion_classes: list[CompletionClass] = []
        all_distances: list[int] = []
        pair_distance: dict[tuple[str, str], int] = {}
        for members in components:
            representative = members[0]
            witnesses = []
            for member in members:
                witness = cls._shortest_path(representative, member, adjacency)
                witnesses.append(witness)
            completion_classes.append(
                CompletionClass(
                    id=class_of[representative],
                    representative=representative,
                    members=members,
                    finite_reach_from_representative=witnesses,
                )
            )
            for source in members:
                for target in members:
                    witness = cls._shortest_path(source, target, adjacency)
                    assert witness.length is not None
                    pair_distance[(source, target)] = witness.length
                    all_distances.append(witness.length)

        max_distance = max(all_distances, default=0)
        generation_stages: list[GenerationStage] = []
        previous_count = 0
        for index in range(max_distance + 1):
            count = sum(int(distance <= index) for distance in pair_distance.values())
            generation_stages.append(
                GenerationStage(
                    index=index,
                    related_ordered_pairs=count,
                    newly_related_ordered_pairs=count - previous_count,
                )
            )
            previous_count = count

        def value_key(value: Any) -> str:
            return _stable(value)

        reading_receipts: list[ReadingReceipt] = []
        for reading in data.readings:
            local = all(
                not step.admitted_for_completion
                or value_key(reading.values[step.source])
                == value_key(reading.values[step.target])
                for step in data.steps
            )
            global_invariant = all(
                len({value_key(reading.values[item]) for item in members}) == 1
                for members in components
            )
            quotient_values: dict[str, Any] | None = None
            if local:
                quotient_values = {
                    class_of[members[0]]: reading.values[members[0]]
                    for members in components
                }
            decides = all(
                (
                    value_key(reading.values[left])
                    == value_key(reading.values[right])
                )
                == (class_of[left] == class_of[right])
                for left in data.presentations
                for right in data.presentations
            )
            range_by_key: dict[str, Any] = {}
            for item in data.presentations:
                range_by_key.setdefault(value_key(reading.values[item]), reading.values[item])
            reading_receipts.append(
                ReadingReceipt(
                    name=reading.name,
                    local_invariant=local,
                    global_invariant=global_invariant,
                    local_iff_global=local == global_invariant,
                    factors_through_completion=local,
                    unique_factorization=local,
                    quotient_values=quotient_values,
                    decides_completion=decides,
                    range_values=list(range_by_key.values()),
                    metadata=reading.metadata,
                )
            )

        truth_receipts: list[TruthReceipt] = []
        for truth in data.truths:
            local = all(
                not step.admitted_for_completion
                or truth.values[step.source] == truth.values[step.target]
                for step in data.steps
            )
            global_invariant = all(
                len({truth.values[item] for item in members}) == 1
                for members in components
            )
            quotient_values = (
                {
                    class_of[members[0]]: truth.values[members[0]]
                    for members in components
                }
                if local
                else None
            )
            truth_receipts.append(
                TruthReceipt(
                    name=truth.name,
                    local_invariant=local,
                    global_invariant=global_invariant,
                    local_iff_global=local == global_invariant,
                    factors_through_completion=local,
                    quotient_values=quotient_values,
                    metadata=truth.metadata,
                )
            )

        canonical_truths = {
            class_of[members[0]]: {
                presentation: class_of[presentation] == class_of[members[0]]
                for presentation in data.presentations
            }
            for members in components
        }
        pushed_equality = all(
            not step.admitted_for_completion
            or class_of[step.source] == class_of[step.target]
            for step in data.steps
        )
        return CompletionEvaluation(
            classes=completion_classes,
            class_of=class_of,
            generation_stages=generation_stages,
            max_finite_witness_length=max_distance,
            every_identification_has_finite_local_path=True,
            no_global_jump=True,
            local_global_reading_equivalent=all(
                item.local_iff_global for item in reading_receipts
            ),
            local_global_truth_equivalent=all(
                item.local_iff_global for item in truth_receipts
            ),
            all_local_truths_recover_completion=True,
            canonical_class_truths=canonical_truths,
            readings=reading_receipts,
            truths=truth_receipts,
            pushed_step_generates_only_equality=pushed_equality,
            completion_closed=pushed_equality,
            completion_idempotent=pushed_equality,
            quotient_map_natural=True,
            universal_factorization_available=True,
            canonical_representative_selected=False,
            truth_issued=False,
        )

    def _source_context(
        self, source_event_id: str | None, source_ids: list[str]
    ) -> tuple[list[str], list[str]]:
        exact_sources = list(source_ids)
        parents: list[str] = []
        if source_event_id is not None:
            event = self.runtime.supernet_store.get_event(source_event_id)
            exact_sources.extend(event["exact_source_ids"])
            parents.append(source_event_id)
        return _unique(exact_sources), parents

