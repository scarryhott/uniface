    async def extend_system(
        self, system_id: str, data: CompletionExtensionCreate
    ) -> dict[str, Any]:
        parent = self.store.get_system(system_id)
        presentations = list(parent["presentations"])
        for item in data.added_presentations:
            if item not in presentations:
                presentations.append(item)
        known = set(presentations)
        for step in data.added_steps:
            if step.source not in known or step.target not in known:
                raise ValueError("every added step endpoint must exist after extension")

        if data.readings is None:
            inherited_readings = parent["readings"]
            if data.added_presentations and inherited_readings:
                raise ValueError(
                    "extensions adding presentations must submit complete replacement readings"
                )
            readings = inherited_readings
        else:
            readings = [item.model_dump(mode="json") for item in data.readings]
        if data.truths is None:
            inherited_truths = parent["truths"]
            if data.added_presentations and inherited_truths:
                raise ValueError(
                    "extensions adding presentations must submit complete replacement truths"
                )
            truths = inherited_truths
        else:
            truths = [item.model_dump(mode="json") for item in data.truths]

        self.runtime.supernet_integrator.transition(
            parent["integration_event_id"],
            IntegrationStateCreate(
                stage=IntegrationStage.REOPENED,
                verdict=Verdict.OPEN,
                reason="New local translations reopen the prior completion stage",
                actor_id=data.authored_by,
                successor_potential=[
                    {
                        "form_type": "completion-extension",
                        "parent_system_id": system_id,
                        "added_presentations": data.added_presentations,
                        "added_steps": [item.model_dump(mode="json") for item in data.added_steps],
                    }
                ],
                metadata={"truth_issued": False, "historical_completion_retained": True},
            ),
        )
        child = CompletionSystemCreate(
            name=f"{parent['name']} — reopened completion",
            authored_by=data.authored_by,
            presentations=presentations,
            steps=[
                LocalTranslationStepInput.model_validate(item)
                for item in parent["steps"]
            ]
            + data.added_steps,
            readings=readings,
            truths=truths,
            source_event_id=data.source_event_id,
            perspective_id=parent.get("perspective_id"),
            problem_id=parent.get("problem_id"),
            source_ids=_unique(parent["source_ids"] + data.source_ids),
            metadata={
                **parent["metadata"],
                **data.metadata,
                "reopens_system_id": system_id,
            },
        )
        return await self.create_system(child, parent_system_id=system_id)

    def reach_witness(self, system_id: str, source: str, target: str) -> dict[str, Any]:
        system = self.store.get_system(system_id)
        if source not in system["presentations"] or target not in system["presentations"]:
            raise KeyError("source and target must be presentations in the completion system")
        adjacency = self._graph(
            system["presentations"],
            [LocalTranslationStepInput.model_validate(item) for item in system["steps"]],
        )
        return self._shortest_path(source, target, adjacency).model_dump(mode="json")

    async def create_map(self, data: CompletionMapCreate) -> dict[str, Any]:
        source = self.store.get_system(data.source_system_id)
        target = self.store.get_system(data.target_system_id)
        if set(data.mapping) != set(source["presentations"]):
            raise ValueError("mapping must assign exactly every source presentation")
        if any(value not in target["presentations"] for value in data.mapping.values()):
            raise ValueError("every mapped value must be a target presentation")

        source_class = source["evaluation"]["class_of"]
        target_class = target["evaluation"]["class_of"]
        relation_preserving = all(
            not step.get("admitted_for_completion", True)
            or target_class[data.mapping[step["source"]]]
            == target_class[data.mapping[step["target"]]]
            for step in source["steps"]
        )
        induced: dict[str, str] | None = None
        map_mk = False
        if relation_preserving:
            induced = {}
            for presentation in source["presentations"]:
                source_cid = source_class[presentation]
                target_cid = target_class[data.mapping[presentation]]
                existing = induced.get(source_cid)
                if existing is not None and existing != target_cid:
                    relation_preserving = False
                    induced = None
                    break
                induced[source_cid] = target_cid
            map_mk = relation_preserving

        identity = (
            data.source_system_id == data.target_system_id
            and all(data.mapping[item] == item for item in source["presentations"])
        )
        map_id = str(uuid.uuid4())
        source_ids, parents = self._source_context(data.source_event_id, [])
        parents.extend([source["integration_event_id"], target["integration_event_id"]])
        exact_text = _stable(
            {
                "NRRF799": "functorial completion map",
                "source_system_id": data.source_system_id,
                "target_system_id": data.target_system_id,
                "mapping": data.mapping,
                "relation_preserving": relation_preserving,
                "induced_class_map": induced,
            }
        )
        receipt = await self.runtime.integrate_resource(
            ResourceEnvelope(
                exact_text=exact_text,
                authored_by=data.authored_by,
                form_label="translational completion map",
                language_label="NRRF799 functoriality chart",
                source_id="translational-completion-supernet",
                capabilities=["map local steps", "induce quotient map", "commute with quotient maps"],
                constraints=["map is determined only when local steps are preserved"],
                relation_hints=["NRRF799", "map", "map_mk", "functorial completion"],
                causal_predecessor_ids=_unique(parents),
                parent_event_ids=_unique(parents),
                affected_perspectives=[data.authored_by],
                evidence_status=EvidenceStatus.FORMALLY_PROVED_UNDER_READING,
                adapter_label="completion",
                external_key=f"completion:map:{map_id}",
                metadata={
                    **data.metadata,
                    "map_id": map_id,
                    "parent_map_ids": data.parent_map_ids,
                    "relation_preserving": relation_preserving,
                    "truth_issued": False,
                },
            )
        )
        row = {
            "id": map_id,
            "occurrence_id": receipt["occurrence_ids"][0],
            "integration_event_id": receipt["event_id"],
            "source_system_id": data.source_system_id,
            "target_system_id": data.target_system_id,
            "mapping": data.mapping,
            "relation_preserving": relation_preserving,
            "induced_class_map": induced,
            "map_mk_commutes": map_mk,
            "identity_map": identity,
            "parent_map_ids": data.parent_map_ids,
            "authored_by": data.authored_by,
            "source_event_id": data.source_event_id,
            "metadata": {**data.metadata, "truth_issued": False},
            "created_at": utcnow(),
        }
        stored = self.store.create_map(row)
        if relation_preserving:
            self.runtime.supernet_integrator.determine(
                receipt["event_id"],
                actor_id=data.authored_by,
                rigidity_scope=["local-step preservation", "induced quotient map"],
                rigidity_receipt={
                    "relation_preserving": True,
                    "map_mk_commutes": True,
                    "identity_law": identity,
                    "canonical_representative_selected": False,
                },
                determined_form={
                    "map_id": map_id,
                    "induced_class_map": induced,
                    "canonical_representative": None,
                },
                reason="The local-step-preserving map induces one map of natural completions",
            )
        self.runtime.supernet_integrator.transition(
            receipt["event_id"],
            IntegrationStateCreate(
                stage=IntegrationStage.RETURNED,
                verdict=Verdict.OPEN,
                reason="The completion map returns without issuing a truth verdict",
                actor_id=data.authored_by,
                returned_resource_ids=[map_id],
                metadata={"relation_preserving": relation_preserving, "truth_issued": False},
            ),
        )
        self.projection()
        return self.store.get_map(stored["id"])

    async def compose_maps(self, data: CompletionMapComposeCreate) -> dict[str, Any]:
        first = self.store.get_map(data.first_map_id)
        second = self.store.get_map(data.second_map_id)
        if first["target_system_id"] != second["source_system_id"]:
            raise ValueError("first map target must equal second map source")
        composed = {
            source: second["mapping"][middle]
            for source, middle in first["mapping"].items()
        }
        return await self.create_map(
            CompletionMapCreate(
                source_system_id=first["source_system_id"],
                target_system_id=second["target_system_id"],
                mapping=composed,
                authored_by=data.authored_by,
                parent_map_ids=[data.first_map_id, data.second_map_id],
                metadata={**data.metadata, "composition_law": True},
            )
        )

    def projection(self) -> dict[str, Any]:
        systems = self.store.list_systems()
        maps = self.store.list_maps()
        projection = {
            "generated_at": utcnow(),
            "systems": systems,
            "maps": maps,
            "stats": self.store.stats(),
            "source_reverse_index": {
                **{
                    f"completion:{item['id']}": list(item["source_ids"])
                    for item in systems
                },
                **{
                    f"completion-map:{item['id']}": list(
                        self.runtime.supernet_store.get_event(item["integration_event_id"])[
                            "exact_source_ids"
                        ]
                    )
                    for item in maps
                },
            },
            "formal_readings": ["NRRF798", "NRRF799"],
            "canonical_runtime_operation": "integrate",
            "local_global_same_completion": True,
            "every_global_identification_requires_finite_local_lineage": True,
            "truth_issued": False,
        }
        self.store.set_state("completion_field_projection", projection)
        return projection
